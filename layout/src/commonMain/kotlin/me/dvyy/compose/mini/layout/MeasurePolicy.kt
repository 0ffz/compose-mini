package me.dvyy.compose.mini.layout

import androidx.compose.runtime.Stable
import me.dvyy.compose.mini.layout.jetpack.Constraints
import me.dvyy.compose.mini.layout.jetpack.IntOffset
import me.dvyy.compose.mini.layout.jetpack.IntSize

data class MeasureResult(
    val width: Int,
    val height: Int,
    val placer: Placer,
)

@Stable
fun interface MeasurePolicy {
    fun measure(measurables: List<Measurable>, constraints: Constraints): MeasureResult
}

@Stable
fun interface Placer {
    fun placeChildren()
}

interface Measurable {
    fun measure(constraints: Constraints): Placeable
}

interface Placeable {
    var width: Int
    var height: Int

    fun placeAt(x: Int, y: Int)

    fun placeAt(offset: IntOffset) = placeAt(offset.x, offset.y)

    val size: IntSize get() = IntSize(width, height)
}


